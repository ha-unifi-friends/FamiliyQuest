#!/usr/bin/env python3
"""Collect every mdi:… icon name the planer uses and write web/planer/mdi-icons.js with their SVG paths.

Paths come from @mdi/js (Material Design Icons, Apache 2.0 – Pictogrammers). Needs the unpacked package:
    npm pack @mdi/js@7.4.47 && tar xzf mdi-js-7.4.47.tgz
    python3 tools/build_planer_icons.py package/mdi.js
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCES = [ROOT / "family_quest/app/web/planer/src", ROOT / "family_quest/app/familyquest/planer"]
EXTRA = ["help-circle-outline", "chevron-up", "chevron-down", "chevron-left", "chevron-right"]  # fallback + mdi:chevron-${dir}


def camel(name: str) -> str:
    return "mdi" + "".join(p[:1].upper() + p[1:] for p in name.split("-"))


def main(mdi_js: str) -> None:
    paths = dict(re.findall(r'export var (mdi\w+) = "([^"]+)"', Path(mdi_js).read_text()))
    if not paths:
        paths = dict(re.findall(r'export const (mdi\w+) = "([^"]+)"', Path(mdi_js).read_text()))
    names = set(EXTRA)
    for base in SOURCES:
        for f in base.rglob("*"):
            if f.suffix in (".js", ".py"):
                names.update(re.findall(r"mdi:([a-z0-9-]+)", f.read_text(encoding="utf-8", errors="ignore")))
    out, missing = {}, []
    for n in sorted(names):
        p = paths.get(camel(n))
        if p:
            out[n] = p
        else:
            missing.append(n)
    target = ROOT / "family_quest/app/web/planer/mdi-icons.js"
    target.write_text("// Material Design Icons (Apache 2.0, Pictogrammers) used by the planer – generated by tools/build_planer_icons.py\n"
                      "window.FP_MDI = " + json.dumps(out, separators=(",", ":")) + ";\n", encoding="utf-8")
    print(f"{len(out)} icons → {target.relative_to(ROOT)}; not found: {missing}")


if __name__ == "__main__":
    main(sys.argv[1])
